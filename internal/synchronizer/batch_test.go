func TestManagerSkipsUnchangedFilesAndReportsStaleDocuments(t *testing.T) {
	t.Parallel()

	projectRoot := t.TempDir()
	writeSourceFile(t, projectRoot, "internal/demo/demo.go", "package demo\n\nfunc Hello() {}\n")
	writeSourceFile(t, projectRoot, "vendor/ignored.go", "package vendor\n")
	writeSourceFile(t, projectRoot, ".hidden/ignored.go", "package hidden\n")

	memoryRoot := t.TempDir()
	writeSourceFile(t, memoryRoot, "index.memory", "---\ntype: index\ngaps: []\n---\n\n# Memory Index\n")
	store, err := memory.NewRepository(memoryRoot)
	if err != nil {
		t.Fatalf("NewRepository() error = %v", err)
	}
	source, err := NewSourceRepository(projectRoot)
	if err != nil {
		t.Fatalf("NewSourceRepository() error = %v", err)
	}
	service := NewService(source, store, fakeLLM{response: generatedDemoMemory})
	manager := NewManager(source, store, service)

	report, err := manager.Run(context.Background(), RunOptions{Workers: 2})
	if err != nil {
		t.Fatalf("Run() error = %v", err)
	}
	if len(report.Created) != 1 || report.Created[0] != "internal/demo/demo.go.memory" {
		t.Fatalf("Run() created = %v", report.Created)
	}

	report, err = manager.Run(context.Background(), RunOptions{Workers: 2})
	if err != nil {
		t.Fatalf("Run() unchanged error = %v", err)
	}
	if len(report.Unchanged) != 1 || report.Unchanged[0] != "internal/demo/demo.go.memory" {
		t.Fatalf("Run() unchanged = %v", report.Unchanged)
	}

	if err := os.WriteFile(filepath.Join(projectRoot, "internal", "demo", "demo.go"), []byte("package demo\n\nfunc Hello(name string) {}\n"), 0o600); err != nil {
		t.Fatalf("WriteFile() error = %v", err)
	}
	report, err = manager.Run(context.Background(), RunOptions{Status: true})
	if err != nil {
		t.Fatalf("Run() status error = %v", err)
	}
	if len(report.Stale) != 1 || report.Stale[0] != "internal/demo/demo.go.memory" {
		t.Fatalf("Run() stale = %v", report.Stale)
	}
}

func TestManagerReportsOrphansAndReconcilesIndexes(t *testing.T) {
	t.Parallel()

	projectRoot := t.TempDir()
	writeSourceFile(t, projectRoot, "demo.go", "package demo\n")
	memoryRoot := t.TempDir()
	writeSourceFile(t, memoryRoot, "index.memory", "---\ntype: index\ngaps: []\n---\n\n# Memory Index\n\n- memory/orphan.go.memory\n")
	writeSourceFile(t, memoryRoot, "orphan.go.memory", "---\ntype: source\nsource_hash: stale\ngaps: []\n---\n\n# Summary\n\n- Old.\n")

	store, err := memory.NewRepository(memoryRoot)
	if err != nil {
		t.Fatalf("NewRepository() error = %v", err)
	}
	source, err := NewSourceRepository(projectRoot)
	if err != nil {
		t.Fatalf("NewSourceRepository() error = %v", err)
	}
	manager := NewManager(source, store, NewService(source, store, fakeLLM{response: generatedNoExportsMemory}))

	report, err := manager.Run(context.Background(), RunOptions{Status: true})
	if err != nil {
		t.Fatalf("Run() error = %v", err)
	}
	if len(report.Orphaned) != 1 || report.Orphaned[0] != "orphan.go.memory" {
		t.Fatalf("Run() orphaned = %v", report.Orphaned)
	}

	report, err = manager.Run(context.Background(), RunOptions{Status: true, Fix: true})
	if err != nil {
		t.Fatalf("Run() fix error = %v", err)
	}
	if len(report.Orphaned) != 1 {
		t.Fatalf("Run() fixed orphaned = %v", report.Orphaned)
	}
	index, err := store.ReadProjectIndex(context.Background())
	if err != nil {
		t.Fatalf("ReadProjectIndex() error = %v", err)
	}
	if containsString(index.Content, "orphan.go.memory") {
		t.Fatalf("project index retains orphan: %s", index.Content)
	}
}

func TestSourceRepositoryDiscoveryKeepsInternalMemoryPackage(t *testing.T) {
	t.Parallel()

	projectRoot := t.TempDir()
	writeSourceFile(t, projectRoot, "internal/memory/repository.go", "package memory\n")
	writeSourceFile(t, projectRoot, "memory/ignored.go", "package memory\n")
	writeSourceFile(t, projectRoot, "generated.go", "// Code generated by test; DO NOT EDIT.\npackage demo\n")
	source, err := NewSourceRepository(projectRoot)
	if err != nil {
		t.Fatalf("NewSourceRepository() error = %v", err)
	}

	paths, err := source.Discover(context.Background(), DiscoverOptions{})
	if err != nil {
		t.Fatalf("Discover() error = %v", err)
	}
	if got, want := strings.Join(paths, ","), "internal/memory/repository.go"; got != want {
		t.Fatalf("Discover() paths = %q, want %q", got, want)
	}
}

const generatedDemoMemory = `{"summary":"Provides a greeting.","summary_evidence":{"symbol":"file","start_line":1,"end_line":1,"kind":"file"},"exports":[{"symbol":"Hello","summary":"Provides a greeting.","start_line":3,"end_line":3,"kind":"declaration"}],"dependencies":[],"rules":[],"test_scenarios":[],"gaps":[]}`
const generatedNoExportsMemory = `{"summary":"Defines the demo package.","summary_evidence":{"symbol":"file","start_line":1,"end_line":1,"kind":"file"},"exports":[],"dependencies":[],"rules":[],"test_scenarios":[],"gaps":[]}`

func writeSourceFile(t *testing.T, root, path, content string) {
	t.Helper()
	fullPath := filepath.Join(root, path)
	if err := os.MkdirAll(filepath.Dir(fullPath), 0o750); err != nil {
		t.Fatalf("MkdirAll() error = %v", err)
	}
	if err := os.WriteFile(fullPath, []byte(content), 0o600); err != nil {
		t.Fatalf("WriteFile() error = %v", err)
	}
}

func containsString(value, wanted string) bool {
	return strings.Contains(value, wanted)
}
